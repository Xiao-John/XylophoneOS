"""Bind this unpacked SDK tree into a local xos_app/xypm profile (written outside the SDK)."""
import argparse
import json
from pathlib import Path

from xos_app import tree_receipt

SDK = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('-o', '--output', type=Path, required=True,
                        help='profile JSON path; must be OUTSIDE the SDK directory')
    args = parser.parse_args()
    out = args.output.resolve()
    if SDK in out.parents or out == SDK:
        raise SystemExit('refuse to write profile inside the SDK tree (would change its hash)')
    meta = json.loads((SDK / 'manifest.json').read_text())
    digest, _ = tree_receipt(SDK)
    base = json.loads((SDK / 'config/package/xos_x86_64_static_single_v1.json').read_text())
    profile = dict(base)
    profile['id'] = 'xos-x86_64-sdk-local'
    profile['scope'] = 'local profile bound to this unpacked SDK tree; generated by adopt_sdk.py'
    profile['evidence'] = 'tools/adopt_sdk.py'
    profile['sdk_tree_sha256'] = [digest]
    profile['verified_system_builds'] = [meta.get('build_id', '')]
    out.write_text(json.dumps(profile, indent=2, ensure_ascii=False) + '\n')
    print(json.dumps({'profile': str(out), 'id': profile['id'],
                      'sdk_tree_sha256': digest,
                      'build_id': meta.get('build_id')}, indent=2))


if __name__ == '__main__':
    main()
