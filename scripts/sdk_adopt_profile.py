"""Bind this unpacked SDK tree into an xos_app/xypm profile (written outside the SDK)."""
import argparse
import json
from pathlib import Path

from xos_app import tree_receipt

SDK = Path(__file__).resolve().parents[1]


def resolve_base(value):
    if value is None:
        return SDK / 'config/package/xos_x86_64_static_single_v1.json'
    path = value if value.is_absolute() else Path.cwd() / value
    if not path.is_file():
        path = SDK / value
    if not path.is_file():
        raise SystemExit('base profile not found: ' + str(value))
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('-o', '--output', type=Path, required=True,
                        help='profile JSON path; must be OUTSIDE the SDK directory')
    parser.add_argument('--base-profile', type=Path,
                        help='base profile JSON; relative paths are resolved from CWD, then the SDK')
    parser.add_argument('--id',
                        help='profile id override; defaults to the base id, or xos-x86_64-sdk-local for the v1 default')
    args = parser.parse_args()
    out = args.output.resolve()
    if SDK in out.parents or out == SDK:
        raise SystemExit('refuse to write profile inside the SDK tree (would change its hash)')
    meta = json.loads((SDK / 'manifest.json').read_text())
    digest, _ = tree_receipt(SDK)
    base = json.loads(resolve_base(args.base_profile).read_text())
    profile = dict(base)
    if args.id:
        profile['id'] = args.id
    elif args.base_profile is None:
        profile['id'] = 'xos-x86_64-sdk-local'
    profile['scope'] = ('profile bound to this unpacked SDK tree; generated by adopt_sdk.py; '
                        'use the base id for a release work disk')
    profile['evidence'] = 'tools/adopt_sdk.py'
    profile['sdk_tree_sha256'] = [digest]
    profile['verified_system_builds'] = [meta.get('build_id', '')]
    out.write_text(json.dumps(profile, indent=2, ensure_ascii=False) + '\n')
    print(json.dumps({'profile': str(out), 'id': profile['id'],
                      'base_profile': base['id'],
                      'sdk_tree_sha256': digest,
                      'build_id': meta.get('build_id')}, indent=2))


if __name__ == '__main__':
    main()
