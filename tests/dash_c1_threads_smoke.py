"""Guest C1 pipe wait/close races using the mechanism-only thread core, no newlib."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT/'scripts'), str(ROOT/'tests')]
from boot_smoke import Guest
from make_work_disk import create_fat32
from process_smoke import command, resources
from task_smoke import send_bytes, pump
from toolchain import COMMON_FLAGS, X86_FLAGS, tool
from work_disk import transfer


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--system', type=Path, default=ROOT/'build')
    parser.add_argument('--report', type=Path, default=ROOT/'build/dash_c1_threads_report.json')
    parser.add_argument('--artifacts', type=Path, default=ROOT/'build/dash_c1_threads_evidence')
    parser.add_argument('--repeat', type=int, default=3)
    args = parser.parse_args()
    if not 1 <= args.repeat <= 5:
        parser.error('--repeat must be between 1 and 5')
    args.system = args.system.resolve()
    args.artifacts = args.artifacts.resolve()
    args.artifacts.mkdir(parents=True, exist_ok=True)
    source = ROOT/'tests/fixtures/dash_c1/pipe_threads.cpp'
    sdk = args.system/'sdk'
    core = args.system/'threading_core/libxos_thread_core.a'
    target_tools = ROOT/'build/target_tools'
    obj = args.artifacts/'pipe_threads.o'
    probe = args.artifacts/'pipe_threads.elf'
    manifest_path = args.system/'manifest.json'
    report = {
        'status': 'failed', 'scope': 'C1 blocking pipe readiness and thread lifecycle; mechanism-only runtime',
        'source_commit': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
        'source_files': {}, 'system': {}, 'sdk_inputs': {}, 'tools': {},
        'build_commands': [], 'runs': [], 'checks': [],
        'not_run': ['pthread_or_newlib_threaded_pipe_io', 'SMP', 'long_randomized_stress'],
    }
    guest = None
    try:
        manifest = json.loads(manifest_path.read_text())
        sdk_manifest = json.loads((sdk/'manifest.json').read_text())
        image = args.system/'xos.img'
        report['system'] = {'build_id': manifest['build_id'], 'manifest_sha256': sha(manifest_path),
                            'image_sha256': sha(image)}
        if report['system']['image_sha256'] != manifest['artifacts']['xos.img']['sha256']:
            raise AssertionError('system image differs from its build manifest')
        if sdk_manifest['build_id'] != manifest['build_id']:
            raise AssertionError('SDK and kernel belong to different builds')
        for relative in ('tests/fixtures/dash_c1/pipe_threads.cpp', 'tests/dash_c1_threads_smoke.py',
                         'src/user/include/xos/thread_core.hpp', 'src/user/arch/x86_64/thread_core.cpp',
                         'src/shared/include/xos/process_abi.hpp', 'src/shared/include/xos/thread_abi.hpp',
                         'src/kernel/core/thread_lifecycle.hpp', 'src/kernel/arch/x86_64/tasks.cpp'):
            report['source_files'][relative] = sha(ROOT/relative)
        for path in (sdk/'manifest.json', sdk/'crt0.o', sdk/'user.ld', sdk/'lib/libxos.a',
                     sdk/'lib/libxos_loader.a', core,
                     *sorted((sdk/'include/xos').glob('*.hpp'))):
            report['sdk_inputs'][str(path.relative_to(args.system))] = sha(path)
        # The core archive is generated by the system build. It must still match
        # that build, rather than merely having a plausible filename.
        core_artifact = manifest.get('artifacts', {}).get(str(core.relative_to(args.system)))
        if core_artifact is not None and sha(core) != core_artifact['sha256']:
            raise AssertionError('thread core archive differs from system manifest')
        compiler = tool('g++')
        for name, path in (('g++', Path(compiler)), ('as', target_tools/'as'), ('ld', target_tools/'ld')):
            if not path.is_file():
                raise AssertionError(f'missing target tool {path}; prepare cross-tool aliases before this test')
            report['tools'][name] = {'path': str(path.resolve()), 'sha256': sha(path),
                'version': subprocess.check_output([str(path), '--version'], text=True).splitlines()[0]}

        def build(command_line, log_name):
            report['build_commands'].append([str(item) for item in command_line])
            result = subprocess.run(command_line, capture_output=True, text=True)
            (args.artifacts/log_name).write_text(result.stdout+result.stderr)
            if result.returncode:
                raise AssertionError(f'probe build failed ({result.returncode}), see {log_name}')

        isa = [flag for flag in X86_FLAGS if flag != '-mgeneral-regs-only']
        build([compiler, '-B'+str(target_tools)+'/', *COMMON_FLAGS, *isa,
               '-ftls-model=local-exec', '-I', str(sdk/'include'),
               '-I', str(ROOT/'src/user/include'), '-c', str(source), '-o', str(obj)], 'compile.log')
        build([compiler, '-B'+str(target_tools)+'/', *X86_FLAGS, '-nostdlib', '-static', '-no-pie',
               '-Wl,--build-id=none,--no-undefined,--fatal-warnings,-z,noexecstack,-z,max-page-size=4096',
               '-T', str(sdk/'user.ld'), str(sdk/'crt0.o'), str(obj),
               '-Wl,--start-group', str(core), str(sdk/'lib/libxos.a'),
               str(sdk/'lib/libxos_loader.a'), '-Wl,--end-group', '-o', str(probe)], 'link.log')
        report['probe'] = {'path': str(probe), 'sha256': sha(probe), 'bytes': probe.stat().st_size,
                           'object_sha256': sha(obj)}
        with tempfile.TemporaryDirectory(prefix='xos_c1_threads_') as folder_name:
            folder = Path(folder_name)
            private_image = folder/'boot.img'
            shutil.copyfile(image, private_image)
            disk = folder/'work.img'
            create_fat32(disk, 512)
            transfer(disk, 'mkdir', '/tests')
            transfer(disk, 'import', '/tests/pipe_threads', probe)
            guest = Guest(private_image, 'dash_c1_threads', work_disk=disk)
            report['qemu_command'] = guest.command
            qemu = Path(guest.command[0])
            report['tools']['qemu'] = {'path': str(qemu.resolve()), 'sha256': sha(qemu),
                'version': subprocess.check_output([str(qemu), '--version'], text=True).splitlines()[0]}
            guest.expect(b'xos64> ', timeout=40)
            send_bytes(guest, b'run\r')
            guest.expect_supervisor(trace=True, timeout=40)
            pump(guest, 1.5)
            baseline = resources(guest)
            report['baseline_resources'] = baseline
            markers = (
                b'C1_THREADS two_empty_read_waiters=ok',
                b'C1_THREADS full_write_wait_read_wake=ok',
                b'C1_THREADS check_enqueue_race_rounds=64 preexisting_readiness=ok',
                b'C1_THREADS close_last_writer_eof=ok close_last_reader_epipe=ok',
                b'C1_THREADS close_wait_token_with_same_direction_alias=ok',
                b'C1_THREADS resources=baseline PASS',
            )
            for iteration in range(args.repeat):
                run = {'iteration': iteration, 'command': 'exec-driver /tests/pipe_threads',
                       'expected_exit': 0, 'expected_output': [value.decode() for value in markers],
                       'expected_resources': baseline, 'status': 'failed'}
                report['runs'].append(run)
                start = len(guest.output)
                try:
                    output = command(guest, run['command'], b'kind=exited code=', timeout=90)
                    run['output'] = output.decode(errors='replace')
                    if b'C1_THREADS_FAIL' in output or b'C1_THREADS_TIMEOUT' in output:
                        raise AssertionError(f'guest probe failure/watchdog in iteration {iteration}')
                    if b'kind=exited code=0' not in output:
                        raise AssertionError(f'guest probe did not exit zero in iteration {iteration}')
                    for marker in markers:
                        if marker not in output:
                            raise AssertionError(f'guest missing {marker!r} in iteration {iteration}')
                    after = resources(guest)
                    run['actual_resources'] = after
                    if after != baseline:
                        raise AssertionError(f'guest resources {after} differ from baseline {baseline}')
                    run.update(status='passed', actual_exit=0)
                finally:
                    log = args.artifacts/f'iteration_{iteration}.serial.log'
                    log.write_bytes(bytes(guest.output[start:]))
                    run['serial_log'] = {'path': str(log), 'sha256': sha(log)}
            report['final_resources'] = resources(guest)
            report['checks'] = [value.decode() for value in markers]
            report['checks'].append(f'{args.repeat} runs preserve supervisor resource baseline')
            report['status'] = 'passed'
    except Exception as error:
        report['error'] = str(error)
        if guest is not None:
            report['output_tail'] = bytes(guest.output[-16000:]).decode(errors='replace')
        raise
    finally:
        if guest is not None:
            serial = args.artifacts/'all.serial.log'
            serial.write_bytes(bytes(guest.output))
            report['serial_log'] = {'path': str(serial), 'sha256': sha(serial)}
            guest.close()
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
